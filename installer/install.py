#!/usr/bin/env python3
"""Installs the kvist agent binary as a `kvist` command, on Linux or Windows.

If a prebuilt binary isn't found, builds one first: creates/reuses a venv
next to this script, installs requirements.txt + pyinstaller into it, and
runs pyinstaller against kvist.spec.

Either way, the resulting binary (core + terminal frontend bundled together
by PyInstaller) is copied into a per-user data dir, and a small `kvist`
launcher is placed on a per-user bin dir. The launcher's job: `kvist` with
no arguments starts the agent with --workspace set to whatever directory you
ran it from, since the binary itself requires --workspace and has no default.
"""

from __future__ import annotations

import argparse
import os
import platform
import shlex
import shutil
import stat
import subprocess
import sys
import tempfile
from pathlib import Path

IS_WINDOWS = platform.system() == "Windows"

PROJECT_ROOT = Path(__file__).resolve().parent.parent
SPEC_FILE = PROJECT_ROOT / "kvist.spec"
REQUIREMENTS_FILE = PROJECT_ROOT / "requirements.txt"
# Dedicated venv, kept separate from the project's own dev .venv so building
# never touches (or has to match the interpreter of) the dev environment.
VENV_DIR = PROJECT_ROOT / ".venv-build"

BINARY_NAME = "kvist.exe" if IS_WINDOWS else "kvist"
CORE_NAME = "kvist-core.exe" if IS_WINDOWS else "kvist-core"
WRAPPER_NAME = "kvist.cmd" if IS_WINDOWS else "kvist"

if IS_WINDOWS:
    DEFAULT_LIB_DIR = Path(os.environ.get("LOCALAPPDATA", str(Path.home() / "AppData" / "Local"))) / "Kvist"
    DEFAULT_BIN_DIR = DEFAULT_LIB_DIR / "bin"
else:
    DEFAULT_LIB_DIR = Path.home() / ".local" / "share" / "kvist"
    DEFAULT_BIN_DIR = Path.home() / ".local" / "bin"

UNIX_WRAPPER = """#!/usr/bin/env bash
# Auto-generated by install.py. Re-run install.py to update.
CORE={core_path}
# --workspace comes first so extra flags do not have to repeat it; argparse
# keeps the last occurrence, so an explicit --workspace still wins.
exec "$CORE" --workspace "$PWD" "$@"
"""

WINDOWS_WRAPPER = """@echo off
setlocal
set "KVIST_CORE={core_path}"
"%KVIST_CORE%" --workspace "%CD%" %*
exit /b %ERRORLEVEL%
"""


def venv_python(venv_dir: Path) -> Path:
    if IS_WINDOWS:
        return venv_dir / "Scripts" / "python.exe"
    return venv_dir / "bin" / "python"


def _has_shared_libpython(python_exe: str) -> bool:
    if IS_WINDOWS:
        return True
    try:
        result = subprocess.run(
            [python_exe, "-c", "import sysconfig; print(sysconfig.get_config_var('Py_ENABLE_SHARED'))"],
            capture_output=True,
            text=True,
            check=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return False
    return result.stdout.strip() == "1"


def find_base_python() -> str:
    """Pick an interpreter PyInstaller can actually link against.

    Some systems have a python3 earlier on PATH that was built without
    --enable-shared (fine for normal use, but PyInstaller refuses it). Prefer
    sys.executable, but fall back to other interpreters on PATH that do have
    a shared libpython.
    """
    if IS_WINDOWS:
        return sys.executable

    candidates = [sys.executable, "python3", "/usr/bin/python3", "python"]
    seen: set[str] = set()
    for candidate in candidates:
        resolved = shutil.which(candidate) or candidate
        if resolved in seen or not Path(resolved).is_file():
            continue
        seen.add(resolved)
        if _has_shared_libpython(resolved):
            return resolved

    raise SystemExit(
        "error: no Python interpreter with a shared libpython was found (PyInstaller "
        "requires one). Install a python3 built with --enable-shared (e.g. via your "
        "system package manager) and re-run."
    )


def ensure_build_venv() -> Path:
    python_path = venv_python(VENV_DIR)
    if python_path.is_file() and not _has_shared_libpython(str(python_path)):
        print(f"{VENV_DIR} was built with an interpreter PyInstaller can't use; recreating ...")
        shutil.rmtree(VENV_DIR)

    if not python_path.is_file():
        base_python = find_base_python()
        print(f"Creating build venv at {VENV_DIR} using {base_python} ...")
        subprocess.check_call([base_python, "-m", "venv", str(VENV_DIR)])

    print("Installing build dependencies ...")
    subprocess.check_call([str(python_path), "-m", "pip", "install", "--upgrade", "pip"])
    if REQUIREMENTS_FILE.is_file():
        subprocess.check_call([str(python_path), "-m", "pip", "install", "-r", str(REQUIREMENTS_FILE)])
    subprocess.check_call([str(python_path), "-m", "pip", "install", "--upgrade", "pyinstaller"])
    return python_path


def build_binary() -> Path:
    if not SPEC_FILE.is_file():
        raise SystemExit(f"error: spec file not found: {SPEC_FILE}")

    python_path = ensure_build_venv()

    print("Building binary with PyInstaller ...")
    subprocess.check_call(
        [str(python_path), "-m", "PyInstaller", "--noconfirm", "--clean", str(SPEC_FILE)],
        cwd=PROJECT_ROOT,
    )

    built = PROJECT_ROOT / "dist" / BINARY_NAME
    if not built.is_file():
        raise SystemExit(f"error: build finished but binary not found at {built}")
    return built


def find_default_binary() -> Path | None:
    candidate = PROJECT_ROOT / "dist" / BINARY_NAME
    return candidate if candidate.is_file() else None


def is_already_installed(lib_dir: Path) -> bool:
    return (lib_dir / CORE_NAME).is_file()


def make_executable(path: Path) -> None:
    if IS_WINDOWS:
        return
    mode = path.stat().st_mode
    path.chmod(mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def install(binary: Path, lib_dir: Path, bin_dir: Path) -> Path:
    if not binary.is_file():
        raise SystemExit(f"error: binary not found: {binary}")

    if lib_dir.exists() and not lib_dir.is_dir():
        raise SystemExit(f"error: library path is not a directory: {lib_dir}")
    if bin_dir.exists() and not bin_dir.is_dir():
        raise SystemExit(f"error: binary path is not a directory: {bin_dir}")
    lib_dir.mkdir(parents=True, exist_ok=True)
    bin_dir.mkdir(parents=True, exist_ok=True)
    core_path = lib_dir / CORE_NAME
    wrapper_path = bin_dir / WRAPPER_NAME
    core_tmp = Path(tempfile.mkstemp(prefix=f".{CORE_NAME}.", dir=lib_dir)[1])
    wrapper_tmp = Path(tempfile.mkstemp(prefix=f".{WRAPPER_NAME}.", dir=bin_dir)[1])
    try:
        shutil.copy2(binary, core_tmp)
        make_executable(core_tmp)
        template = WINDOWS_WRAPPER if IS_WINDOWS else UNIX_WRAPPER
        core_literal = str(core_path) if IS_WINDOWS else shlex.quote(str(core_path))
        wrapper_text = template.format(core_path=core_literal)
        if IS_WINDOWS:
            wrapper_tmp.write_text(wrapper_text.replace("\n", "\r\n"), newline="")
        else:
            wrapper_tmp.write_text(wrapper_text, newline="\n")
        make_executable(wrapper_tmp)

        core_backup = core_path.with_name(f".{core_path.name}.old")
        wrapper_backup = wrapper_path.with_name(f".{wrapper_path.name}.old")
        for backup in (core_backup, wrapper_backup):
            if backup.exists():
                backup.unlink()
        try:
            if core_path.exists():
                core_path.replace(core_backup)
            if wrapper_path.exists():
                wrapper_path.replace(wrapper_backup)
            core_tmp.replace(core_path)
            wrapper_tmp.replace(wrapper_path)
        except BaseException:
            if core_path.exists():
                core_path.unlink()
            if wrapper_path.exists():
                wrapper_path.unlink()
            if core_backup.exists():
                core_backup.replace(core_path)
            if wrapper_backup.exists():
                wrapper_backup.replace(wrapper_path)
            raise
        finally:
            for backup in (core_backup, wrapper_backup):
                if backup.exists():
                    backup.unlink()
    except PermissionError as exc:
        raise SystemExit(
            f"error: cannot overwrite {core_path}. Close every running kvist "
            "session and re-run install.py."
        ) from exc
    finally:
        for temporary in (core_tmp, wrapper_tmp):
            if temporary.exists():
                temporary.unlink()

    return wrapper_path


def path_contains(bin_dir: Path) -> bool:
    entries = os.environ.get("PATH", "").split(os.pathsep)
    target = os.path.normcase(os.path.normpath(str(bin_dir)))
    return any(os.path.normcase(os.path.normpath(e)) == target for e in entries if e)


def add_to_user_path_windows(bin_dir: Path) -> bool:
    """Append bin_dir to the persistent per-user PATH via the registry.

    `setx` truncates PATH at 1024 chars and would mangle a real user's PATH, so
    edit HKCU\\Environment directly, then broadcast the change so newly started
    shells inherit it. Returns True once the entry is present.
    """
    import winreg

    target = os.path.normcase(os.path.normpath(str(bin_dir)))
    try:
        with winreg.OpenKey(
            winreg.HKEY_CURRENT_USER, "Environment", 0, winreg.KEY_READ | winreg.KEY_WRITE
        ) as key:
            try:
                current, value_type = winreg.QueryValueEx(key, "Path")
            except FileNotFoundError:
                current, value_type = "", winreg.REG_EXPAND_SZ
            entries = [e for e in str(current).split(os.pathsep) if e]
            if any(os.path.normcase(os.path.normpath(e)) == target for e in entries):
                return True
            entries.append(str(bin_dir))
            winreg.SetValueEx(
                key, "Path", 0, value_type or winreg.REG_EXPAND_SZ, os.pathsep.join(entries)
            )
    except OSError:
        return False

    _broadcast_environment_change()
    return True


def _broadcast_environment_change() -> None:
    import ctypes

    try:
        ctypes.windll.user32.SendMessageTimeoutW(
            0xFFFF, 0x001A, 0, "Environment", 0x0002, 5000, ctypes.byref(ctypes.c_ulong())
        )
    except (OSError, AttributeError):
        # The PATH entry is already written; a missed broadcast only means
        # already-open programs keep the old environment until relaunch.
        pass


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "binary",
        nargs="?",
        type=Path,
        help=f"Path to a prebuilt {BINARY_NAME}. If omitted and none is found, it gets built.",
    )
    parser.add_argument(
        "--rebuild",
        action="store_true",
        help="Build a fresh binary even if one is already found in dist/.",
    )
    parser.add_argument(
        "--lib-dir",
        type=Path,
        default=DEFAULT_LIB_DIR,
        help=f"Where to store the actual binary (default: {DEFAULT_LIB_DIR}).",
    )
    parser.add_argument(
        "--bin-dir",
        type=Path,
        default=DEFAULT_BIN_DIR,
        help=f"Where to place the `kvist` launcher (default: {DEFAULT_BIN_DIR}).",
    )
    args = parser.parse_args()

    binary = args.binary
    if binary is None:
        # A leftover dist/ binary is only trustworthy on a first install. Once
        # kvist is already installed, re-running install.py means "update", so a
        # stale dist/ artifact must be rebuilt rather than reused.
        reinstalling = is_already_installed(args.lib_dir)
        if args.rebuild:
            binary = build_binary()
        elif reinstalling and find_default_binary() is not None:
            print(f"kvist is already installed and a {BINARY_NAME} exists in dist/; rebuilding it ...")
            binary = build_binary()
        else:
            binary = find_default_binary()
            if binary is None:
                print(f"No {BINARY_NAME} found in dist/, building it ...")
                binary = build_binary()

    wrapper_path = install(binary.resolve(), args.lib_dir, args.bin_dir)

    print(f"Installed core binary to {args.lib_dir / CORE_NAME}")
    print(f"Installed launcher to {wrapper_path}")

    if not path_contains(args.bin_dir):
        if IS_WINDOWS and add_to_user_path_windows(args.bin_dir):
            print(
                f"\nAdded {args.bin_dir} to your user PATH. Open a new terminal, "
                "then run `kvist` in any directory to start the agent there."
            )
        elif IS_WINDOWS:
            print(
                f"\nWarning: could not update PATH automatically. Add {args.bin_dir} "
                "yourself, e.g. in PowerShell:\n"
                '  [Environment]::SetEnvironmentVariable("Path", '
                '[Environment]::GetEnvironmentVariable("Path", "User") + '
                f'";{args.bin_dir}", "User")\n'
                "  (then restart your terminal)"
            )
        else:
            print(
                f"\nWarning: {args.bin_dir} is not on your PATH. Add it, e.g. in fish:\n"
                f"  fish_add_path {args.bin_dir}"
            )
    else:
        print("\nDone. Run `kvist` in any directory to start the agent there.")


if __name__ == "__main__":
    sys.exit(main())
