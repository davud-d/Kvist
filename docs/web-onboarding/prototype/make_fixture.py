"""Write fixture.js for the onboarding prototype from the core's own constants.

The registration address, the role and reasoning descriptions, the provider list
and the built-in model options come from the same modules the web controller
reads, so the prototype carries no value of its own. HOME points at an empty
temporary directory first: nothing is read from the user's ~/.kvist.
Run from the repo root: .venv/bin/python docs/web-onboarding/prototype/make_fixture.py
"""
import json
import os
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
os.environ["HOME"] = os.environ["USERPROFILE"] = tempfile.mkdtemp(prefix="kvist-fixture-")
sys.path.insert(0, str(REPO))

from kernel.llm.anymodel_onboarding import ANYMODEL_REGISTER_URL  # noqa: E402
from kernel.config.config_info import build_config_info  # noqa: E402
from kernel.protocol.core_manifest import build_manifest  # noqa: E402

manifest = build_manifest()
info = build_config_info()
fixture = {
    "registration_url": ANYMODEL_REGISTER_URL,
    "roles": manifest["roles"],
    "effort_levels": manifest["effort_levels"],
    "slash_commands": [c for c in manifest["slash_commands"] if c["name"] in {"new", "provider", "models", "role", "effort", "changes", "help"}],
    "providers": [{"id": p["id"], "label": p["label"], "options": p["options"], "requires_manual_models": p["requires_manual_models"]} for p in info["providers"]],
}
target = Path(__file__).with_name("fixture.js")
target.write_text("// Generated by make_fixture.py from the core; do not edit.\nwindow.FIXTURE = " + json.dumps(fixture, indent=1, ensure_ascii=False) + ";\n", encoding="utf-8")
print(f"{target}: {len(fixture['providers'])} providers, {len(fixture['roles'])} roles, {len(fixture['effort_levels'])} levels")
