_BUTTON_TAGS = {"ButtonClose": "close", "ButtonCloseFocus": "close", "ButtonMin": "min", "ButtonMinFocus": "min",
                "ButtonMax": "max", "ButtonMaxFocus": "max", "ButtonMaxActive": "max", "ButtonMaxActiveFocus": "max"}
_DOCK_WIDTH, _DOCK_HEIGHT, _DOCK_MARGIN, _DOCK_RADIUS = 460, 76, 12, 26
_WALLPAPER_FRAME_SECONDS = 0.14  # the source clip plays at 7 frames per second
# feh paints the root window once per call, so the loop costs nothing between frames.
_WALLPAPER_LOOP = ('while :; do for frame in "$1"/*.jpg; do feh --no-fehbg --bg-fill "$frame"; sleep "$2"; done; done')
_START_TIMEOUT = 15.0
_MESA_EGL = "/usr/share/glvnd/egl_vendor.d/50_mesa.json"


def software_gl_environment() -> dict[str, str]:
    """Pin OpenGL to Mesa's software renderer. Without it libglvnd also probes the host's NVIDIA vendor library,
    which aborts the process in a sandbox that has no GPU device (Xvfb died with SIGABRT inside libEGL_nvidia)."""
    environment = {"LIBGL_ALWAYS_SOFTWARE": "1", "__GLX_VENDOR_LIBRARY_NAME": "mesa"}
    if os.path.exists(_MESA_EGL):
        environment["__EGL_VENDOR_LIBRARY_FILENAMES"] = _MESA_EGL
    return environment

def webview_environment() -> dict[str, str]:
    """WebKitGTK (Tauri, GTK web views) tries GPU composition and DMA-BUF, which has no device in this sandbox and
    died on machines with an NVIDIA driver; the software paths work everywhere."""
    return {"WEBKIT_DISABLE_COMPOSITING_MODE": "1", "WEBKIT_DISABLE_DMABUF_RENDERER": "1", "GDK_BACKEND": "x11",
            "NO_AT_BRIDGE": "1", **software_gl_environment()}


_children: dict[str, subprocess.Popen] = {}
_last_start: tuple[str, str, str, str, str, str] = ()  # display, screen_dir, size, wm, cursors, theme


def start_display(display: str, screen_dir: str, size: str, *, wm: str = "i3", glx: bool = False,
                  cursors: str = "", theme: str = "") -> None:
    global _last_start
    _last_start = (display, screen_dir, size, wm, cursors, theme)
    if cursors:
        # libXcursor reads these, so the window manager and every program started later use the skill's own pointer.
        os.environ.update({"XCURSOR_PATH": cursors, "XCURSOR_THEME": "kvist", "XCURSOR_SIZE": "32"})
    width, height = (int(part) for part in size.lower().split("x", 1))
    number = display.lstrip(":")
    socket_dir = Path("/tmp/.X11-unix")
    # Xvfb run by a normal user does not create this directory itself.
    socket_dir.mkdir(mode=0o1777, exist_ok=True)
    os.chmod(socket_dir, 0o1777)
    command = ["Xvfb", display, "-screen", "0", f"{width}x{height}x24", "-nolisten", "tcp", "-dpi", "96",
               "-nocursor"]
    if not glx:
        command += ["-extension", "GLX"]
    if screen_dir:
        command += ["-fbdir", screen_dir]
    # Every wallpaper frame is an 8 MiB pixmap. glibc raises its mmap threshold as such blocks are freed and then keeps
    # them on the heap: the server grew from 15 to 39 MiB. A fixed threshold returns each one, holding it at 23 MiB.
    environment = {**os.environ, "MALLOC_MMAP_THRESHOLD_": "1000000", **(software_gl_environment() if glx else {})}
    server = subprocess.Popen(command, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=sys.stderr,
                              env=environment)
    _children["server"] = server
    socket_path = socket_dir / f"X{number}"
    deadline = time.monotonic() + _START_TIMEOUT
    while not socket_path.exists():
        if server.poll() is not None:
            raise RuntimeError(f"the virtual screen (Xvfb) exited with status {server.returncode}")
        if time.monotonic() > deadline:
            raise RuntimeError("the virtual screen (Xvfb) did not start")
        time.sleep(0.05)
    os.environ["DISPLAY"] = display
    _children["wm"] = _start_window_manager(wm, theme, width, height)
    if theme and wm == "jwm":
        _children["wallpaper"] = _start_wallpaper(Path(theme) / "wallpaper")
        _round_dock(display, width, height)


def _jwm_config(theme: str, width: int, height: int) -> str:
    buttons = "".join(f"  <{tag}>{Path(theme) / 'buttons' / name}.svg</{tag}>\n" for tag, name in _BUTTON_TAGS.items()) if theme else ""
    return _JWM_CONFIG.format(buttons=buttons, width=width, dock_width=_DOCK_WIDTH, dock_height=_DOCK_HEIGHT,
                              dock_x=(width - _DOCK_WIDTH) // 2, dock_y=height - _DOCK_HEIGHT - _DOCK_MARGIN)


def _start_window_manager(wm: str, theme: str, width: int, height: int) -> subprocess.Popen:
    if wm == "jwm":
        config = Path("/tmp/kvist-jwm.xml")
        config.write_text(_jwm_config(theme, width, height), encoding="utf-8")
        command = ["jwm", "-f", str(config)]
    else:
        config = Path("/tmp/kvist-i3.conf")
        config.write_text(_I3_CONFIG, encoding="utf-8")
        # i3 keeps a 25 MiB shared-memory log unless told otherwise (a config line is read too late for it).
        command = ["i3", "--shmlog-size=0", "-c", str(config)]
    return subprocess.Popen(command, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=sys.stderr)


def _start_wallpaper(frames: Path) -> subprocess.Popen:
    # JWM resets the root background when it starts, so this runs after it.
    return subprocess.Popen(["sh", "-c", _WALLPAPER_LOOP, "wallpaper", str(frames), str(_WALLPAPER_FRAME_SECONDS)],
                            stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def _round_dock(display: str, width: int, height: int) -> None:
    """Cut the dock tray's corners with the X Shape extension, once JWM has mapped it."""
    try:
        from Xlib import X, display as xdisplay
        from Xlib.ext import shape
    except ImportError as error:  # python-xlib is a dependency of the skill, not of the runner
        print(f"the dock keeps square corners: {error}", file=sys.stderr)
        return
    connection = xdisplay.Display(display)
    root = connection.screen().root
    left, top = (width - _DOCK_WIDTH) // 2, height - _DOCK_HEIGHT - _DOCK_MARGIN
    deadline = time.monotonic() + 5
    while time.monotonic() < deadline:
        for window in root.query_tree().children:
            geometry = window.get_geometry()
            if (geometry.x, geometry.y, geometry.width, geometry.height) == (left, top, _DOCK_WIDTH, _DOCK_HEIGHT):
                _apply_round_mask(window, X, shape)
                connection.sync()
                connection.close()
                return
        time.sleep(0.1)
    connection.close()
    print("the dock window did not appear; it keeps square corners", file=sys.stderr)


def _apply_round_mask(window, X, shape) -> None:
    mask = window.create_pixmap(_DOCK_WIDTH, _DOCK_HEIGHT, 1)
    gc = mask.create_gc(foreground=0)
    mask.fill_rectangle(gc, 0, 0, _DOCK_WIDTH, _DOCK_HEIGHT)
    gc.change(foreground=1)
    r, d = _DOCK_RADIUS, _DOCK_RADIUS * 2
    for x, y, start in ((0, 0, 90), (_DOCK_WIDTH - d - 1, 0, 0), (0, _DOCK_HEIGHT - d - 1, 180),
                        (_DOCK_WIDTH - d - 1, _DOCK_HEIGHT - d - 1, 270)):
        mask.fill_arc(gc, x, y, d, d, start * 64, 90 * 64)
    mask.fill_rectangle(gc, r, 0, _DOCK_WIDTH - d, _DOCK_HEIGHT)
    mask.fill_rectangle(gc, 0, r, _DOCK_WIDTH, _DOCK_HEIGHT - d)
    window.shape_mask(shape.SO.Set, shape.SK.Bounding, 0, 0, mask)
    mask.free()


def display_processes() -> dict[str, int]:
    """Pids of the screen's own processes (server, window manager), for memory accounting."""
    return {name: child.pid for name, child in _children.items() if child.poll() is None}


def stop_display() -> None:
    """End the window manager and the server so the screen can be started again with other options."""
    for name in ("wallpaper", "wm", "server"):
        child = _children.pop(name, None)
        if child is None or child.poll() is not None:
            continue
        child.terminate()
        try:
            child.wait(timeout=3)
        except subprocess.TimeoutExpired:
            child.kill()
            child.wait()


def restart_display(*, glx: bool) -> None:
    """Start the same screen again with or without GLX; whatever was running on it is gone."""
    display, screen_dir, size, wm, cursors, theme = _last_start
    stop_display()
    socket_path = Path("/tmp/.X11-unix") / f"X{display.lstrip(':')}"
    deadline = time.monotonic() + 3
    while socket_path.exists() and time.monotonic() < deadline:
        time.sleep(0.05)
    start_display(display, screen_dir, size, wm=wm, glx=glx, cursors=cursors, theme=theme)
