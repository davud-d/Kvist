# -*- coding: utf-8 -*-
"""Claude Code: ``<config>/projects/<folder>/<session id>.jsonl``.

One JSON record per line. ``user`` and ``assistant`` records carry an API
message; a user record whose content holds a ``tool_result`` answers a tool
call and is not a request. Records of sub-agents (``isSidechain``), injected
context (``isMeta``), background-task notices (an ``origin`` other than
``human``) and the summary written after ``/compact`` are not part of the
conversation the person had.
"""
from __future__ import annotations

import os
import re
from dataclasses import replace
from pathlib import Path
from typing import Any

from kernel.session_import.model import (
    ImportedSession,
    ImportedTurn,
    SessionSummary,
    Source,
    head_jsonl,
    iso_to_epoch,
    read_jsonl,
    short_title,
)

_FILE_TOOLS = frozenset({"Edit", "Write", "MultiEdit", "NotebookEdit"})
_SHELL_TOOLS = frozenset({"Bash", "PowerShell"})
_INTERRUPT_PREFIX = "[Request interrupted by user"
_NOISE_PREFIXES = (
    "<local-command-",
    "<command-name>",
    "<command-message>",
    "<command-args>",
    "<bash-input>",
    "<bash-stdout>",
    "<bash-stderr>",
    "Caveat: The messages below were generated by the user",
)
_REMINDER_RE = re.compile(r"<system-reminder>.*?</system-reminder>", re.DOTALL)


def _root(home: Path) -> Path:
    configured = os.environ.get("CLAUDE_CONFIG_DIR")
    return (Path(configured) if configured else home / ".claude") / "projects"


def _user_text(content: Any) -> str | None:
    """The request text of a user message, or None when it answers a tool call."""
    if isinstance(content, str):
        return _REMINDER_RE.sub("", content).strip()
    if not isinstance(content, list):
        return None
    parts: list[str] = []
    for block in content:
        if not isinstance(block, dict):
            continue
        if block.get("type") == "tool_result":
            return None
        if block.get("type") == "text" and isinstance(block.get("text"), str):
            parts.append(_REMINDER_RE.sub("", block["text"]).strip())
    return "\n\n".join(part for part in parts if part)


def _is_request(text: str) -> bool:
    return bool(text) and not text.startswith(_NOISE_PREFIXES)


def _is_conversation(record: dict[str, Any]) -> bool:
    origin = record.get("origin")
    typed_by_person = not isinstance(origin, dict) or origin.get("kind") == "human"
    return (
        record.get("type") in ("user", "assistant")
        and typed_by_person
        and not record.get("isSidechain")
        and not record.get("isMeta")
        and not record.get("isCompactSummary")
        and isinstance(record.get("message"), dict)
    )


def _first_request(records: list[dict[str, Any]]) -> str:
    for record in records:
        if not _is_conversation(record) or record["type"] != "user":
            continue
        text = _user_text(record["message"].get("content"))
        if text and _is_request(text) and not text.startswith(_INTERRUPT_PREFIX):
            return text
    return ""


def find(home: Path, _workspace: Path) -> list[SessionSummary]:
    found: list[SessionSummary] = []
    for path in _root(home).glob("*/*.jsonl"):
        head = head_jsonl(path)
        title = _first_request(head)
        cwd = next((r["cwd"] for r in head if isinstance(r.get("cwd"), str)), "")
        if not title:
            continue
        found.append(
            SessionSummary("claude-code", path.stem, short_title(title), cwd, path.stat().st_mtime, str(path))
        )
    return found


def _absorb_assistant(turn: ImportedTurn, message: dict[str, Any]) -> None:
    content = message.get("content")
    if not isinstance(content, list):
        return
    for block in content:
        if not isinstance(block, dict):
            continue
        if block.get("type") == "text" and str(block.get("text", "")).strip():
            turn.answer = block["text"].strip()
        elif block.get("type") == "tool_use":
            _absorb_tool_call(turn, block)


def _absorb_tool_call(turn: ImportedTurn, block: dict[str, Any]) -> None:
    arguments = block.get("input")
    if not isinstance(arguments, dict):
        return
    if block.get("name") in _FILE_TOOLS:
        turn.note_file(arguments.get("file_path") or arguments.get("notebook_path"))
    elif block.get("name") in _SHELL_TOOLS:
        turn.commands += 1


def load(summary: SessionSummary) -> ImportedSession:
    path = Path(summary.location)
    turns: list[ImportedTurn] = []
    title = ""
    for record in read_jsonl(path):
        if record.get("type") == "ai-title" and isinstance(record.get("aiTitle"), str):
            title = record["aiTitle"]
        if not _is_conversation(record):
            continue
        message = record["message"]
        if record["type"] == "assistant":
            if turns and not record.get("isApiErrorMessage"):
                _absorb_assistant(turns[-1], message)
            continue
        text = _user_text(message.get("content"))
        if text is None:
            continue
        if text.startswith(_INTERRUPT_PREFIX):
            if turns:
                turns[-1].stopped = True
            continue
        if _is_request(text):
            turns.append(ImportedTurn(text, ts=iso_to_epoch(record.get("timestamp"))))
    return ImportedSession(replace(summary, title=title.strip() or summary.title), turns)


SOURCE = Source("claude-code", "Claude Code", "cc", find, load)
