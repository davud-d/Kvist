# -*- coding: utf-8 -*-
"""Turn the first-run key art into the data the setup screen paints.

    python3 backdrop/make_backdrop.py [--source backdrop/kvist-sunset-valley-squirrel-16x9.png] [--width 1280]

Writes ``setup/backdrop-data.ts``: the picture scaled to ``--width`` pixels wide and reduced to
a 256-colour palette PNG (base64). The art is pixel art with flat colour areas, so the palette
costs nothing visible and keeps the bundle, which has to stay one self-contained file, small.
The setup screen shows it as a real image where the terminal can (kitty graphics) and
resamples it to cells elsewhere, so one copy serves every window.

Needs Pillow (dev-time only; the generated file is what ships).
"""
from __future__ import annotations

import argparse
import base64
import io
from pathlib import Path

from PIL import Image

# Paths are relative to the Ink app (frontends/tui/ink), whatever the cwd.
REPO = Path(__file__).resolve().parent.parent
DEFAULT_SOURCE = REPO / "backdrop" / "kvist-sunset-valley-squirrel-16x9.png"
OUTPUT = REPO / "setup" / "backdrop-data.ts"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--width", type=int, default=1280)
    args = parser.parse_args()

    image = Image.open(args.source).convert("RGB")
    height = round(image.height * args.width / image.width)
    small = image.resize((args.width, height), Image.Resampling.LANCZOS)
    palette = small.quantize(colors=256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    out = io.BytesIO()
    palette.save(out, "PNG", optimize=True)
    packed = base64.b64encode(out.getvalue()).decode("ascii")

    OUTPUT.write_text(
        "// Generated by backdrop/make_backdrop.py from backdrop/kvist-sunset-valley-squirrel-16x9.png. Do not edit.\n"
        "// A 256-colour palette PNG, base64.\n"
        f'export const BACKDROP_PNG = "{packed}"\n',
        encoding="utf-8",
    )
    print(f"{OUTPUT.relative_to(REPO)}: {args.width}x{height}, {len(packed)} base64 characters")


if __name__ == "__main__":
    main()
