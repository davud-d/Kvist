// Setup screen copy, English and Russian (Kvist's user-facing strings are bilingual).
export type Locale = "en" | "ru"

export function detectLocale(env: NodeJS.ProcessEnv = process.env): Locale {
  const value = env.KVIST_LANG || env.LC_ALL || env.LC_MESSAGES || env.LANG || ""
  return /^ru/i.test(value) ? "ru" : "en"
}

