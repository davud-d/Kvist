export function FileIcon({ path = "", action = "read_file" }: { path?: string; action?: string }) {
  if (document.getElementById("root")?.dataset.layout !== "workspace") return null
  const name = actionIconName(action, path)
  return <span class="catppuccin-icon" aria-hidden="true" data-icon={name}>
    <img class="cat-mocha" src={mocha[name] ?? mocha._file} alt="" />
    <img class="cat-latte" src={latte[name] ?? latte._file} alt="" />
  </span>
}
