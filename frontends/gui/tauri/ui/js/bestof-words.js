/** The word for `key` in the page's language; an unknown key is shown as it is. */
export const w = (key) => (lang.current === "ru" ? RU : EN)[key] ?? key;

// The council's angles arrive as ids (`executor_id` is the same id); the interface names them.
const ANGLES = { simplicity: "angleSimplicity", security: "angleSecurity", speed: "angleSpeed", maintenance: "angleMaintenance" };

/** The angle's name, or the id itself when the core sent one this interface does not know. */
export const angleName = (angle) => (ANGLES[angle] ? w(ANGLES[angle]) : angle);

/** One line about the angle; empty for an angle this interface does not know. */
export const angleBlurb = (angle) => (ANGLES[angle] ? w(`${ANGLES[angle]}Blurb`) : "");

export const ANGLE_IDS = Object.keys(ANGLES);
