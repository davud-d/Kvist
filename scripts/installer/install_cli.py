def _new_temporary(directory: Path, prefix: str) -> Path:
    """A named temp file whose own descriptor is already closed.

    mkstemp hands back an open descriptor; leaving it open keeps the file
    locked on Windows, where os.replace/unlink then fail with WinError 32.
    """
    descriptor, raw_path = tempfile.mkstemp(prefix=prefix, dir=directory)
    os.close(descriptor)
    return Path(raw_path)


def make_executable(path: Path) -> None:
    if IS_WINDOWS:
        return
    mode = path.stat().st_mode
    path.chmod(mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def clear_quarantine(path: Path) -> None:
    """Drop the quarantine mark a browser puts on a download.

    Gatekeeper refuses to run a quarantined binary that is not notarized. A binary
    built here or fetched with curl carries no mark, so a failure only means there
    was nothing to drop.
    """
    if IS_MACOS:
        probe_command(["xattr", "-d", "com.apple.quarantine", str(path)], timeout=30)


def install_web_launchers(core_path: Path, bin_dir: Path) -> tuple[Path, Path]:
    """Install the web/controller and remote-bridge launchers idempotently."""
    bin_dir.mkdir(parents=True, exist_ok=True)
    core_literal = str(core_path) if IS_WINDOWS else shlex.quote(str(core_path))
    pairs = (
        (
            bin_dir / WEB_WRAPPER_NAME,
            (WINDOWS_WEB_WRAPPER if IS_WINDOWS else UNIX_WEB_WRAPPER).format(
                core_path=core_literal
            ),
        ),
        (
            bin_dir / BRIDGE_WRAPPER_NAME,
            (WINDOWS_BRIDGE_WRAPPER if IS_WINDOWS else UNIX_BRIDGE_WRAPPER).format(
                core_path=core_literal
            ),
        ),
    )
    installed = []
    for target, text in pairs:
        temporary = _new_temporary(bin_dir, f".{target.name}.")
        try:
            temporary.write_text(
                text.replace("\n", "\r\n") if IS_WINDOWS else text,
                newline="" if IS_WINDOWS else "\n",
            )
            make_executable(temporary)
            temporary.replace(target)
        finally:
            temporary.unlink(missing_ok=True)
        installed.append(target)
    return installed[0], installed[1]


def install(binary: Path, lib_dir: Path, bin_dir: Path, status: Status | None = None) -> Path:
    if not binary.is_file():
        raise SystemExit(f"error: binary not found: {binary}")

    if lib_dir.exists() and not lib_dir.is_dir():
        raise SystemExit(f"error: library path is not a directory: {lib_dir}")
    if bin_dir.exists() and not bin_dir.is_dir():
        raise SystemExit(f"error: binary path is not a directory: {bin_dir}")
    lib_dir.mkdir(parents=True, exist_ok=True)
    bin_dir.mkdir(parents=True, exist_ok=True)
    core_path = lib_dir / CORE_NAME
    wrapper_path = bin_dir / WRAPPER_NAME
    core_tmp = _new_temporary(lib_dir, f".{CORE_NAME}.")
    wrapper_tmp = _new_temporary(bin_dir, f".{WRAPPER_NAME}.")
    try:
        show_step(status, STEPS["copy_binary"])
        shutil.copy2(binary, core_tmp)
        make_executable(core_tmp)
        clear_quarantine(core_tmp)
        template = WINDOWS_WRAPPER if IS_WINDOWS else UNIX_WRAPPER
        core_literal = str(core_path) if IS_WINDOWS else shlex.quote(str(core_path))
        wrapper_text = template.format(core_path=core_literal)
        show_step(status, STEPS["create_launcher"])
        if IS_WINDOWS:
            wrapper_tmp.write_text(wrapper_text.replace("\n", "\r\n"), newline="")
        else:
            wrapper_tmp.write_text(wrapper_text, newline="\n")
        make_executable(wrapper_tmp)

        core_backup = core_path.with_name(f".{core_path.name}.old")
        wrapper_backup = wrapper_path.with_name(f".{wrapper_path.name}.old")
        for backup in (core_backup, wrapper_backup):
            if backup.exists():
                backup.unlink()
        try:
            if core_path.exists():
                core_path.replace(core_backup)
            if wrapper_path.exists():
                wrapper_path.replace(wrapper_backup)
            core_tmp.replace(core_path)
            wrapper_tmp.replace(wrapper_path)
        except BaseException:
            if core_path.exists():
                core_path.unlink()
            if wrapper_path.exists():
                wrapper_path.unlink()
            if core_backup.exists():
                core_backup.replace(core_path)
            if wrapper_backup.exists():
                wrapper_backup.replace(wrapper_path)
            raise
        finally:
            for backup in (core_backup, wrapper_backup):
                if backup.exists():
                    backup.unlink()
    except PermissionError as exc:
        raise SystemExit(
            f"error: cannot overwrite {core_path}. Close every running kvist "
            "session and re-run install_cli.py."
        ) from exc
    finally:
        for temporary in (core_tmp, wrapper_tmp):
            if temporary.exists():
                temporary.unlink()

    install_web_launchers(core_path, bin_dir)
    return wrapper_path


def path_contains(bin_dir: Path) -> bool:
    entries = os.environ.get("PATH", "").split(os.pathsep)
    target = os.path.normcase(os.path.normpath(str(bin_dir)))
    return any(os.path.normcase(os.path.normpath(e)) == target for e in entries if e)


def path_hint(bin_dir: Path) -> str:
    """The command that puts bin_dir on PATH for the user's login shell."""
    shell = Path(os.environ.get("SHELL", "")).name
    if shell == "fish":
        return f"fish_add_path {bin_dir}"
    export = f'export PATH="{bin_dir}:$PATH"'
    # Terminal.app starts login shells, which read .bash_profile and not .bashrc.
    rc_files = {"zsh": "~/.zshrc", "bash": "~/.bash_profile" if IS_MACOS else "~/.bashrc"}
    rc_file = rc_files.get(shell)
    return f"echo {shlex.quote(export)} >> {rc_file}" if rc_file else export


def add_to_user_path_windows(bin_dir: Path) -> bool:
    """Append bin_dir to the persistent per-user PATH via the registry.

    `setx` truncates PATH at 1024 chars and would mangle a real user's PATH, so
    edit HKCU\\Environment directly, then broadcast the change so newly started
    shells inherit it. Returns True once the entry is present.
    """
    import winreg

    target = os.path.normcase(os.path.normpath(str(bin_dir)))
    try:
        with winreg.OpenKey(
            winreg.HKEY_CURRENT_USER, "Environment", 0, winreg.KEY_READ | winreg.KEY_WRITE
        ) as key:
            try:
                current, value_type = winreg.QueryValueEx(key, "Path")
            except FileNotFoundError:
                current, value_type = "", winreg.REG_EXPAND_SZ
            entries = [e for e in str(current).split(os.pathsep) if e]
            if any(os.path.normcase(os.path.normpath(e)) == target for e in entries):
                return True
            entries.append(str(bin_dir))
            winreg.SetValueEx(
                key, "Path", 0, value_type or winreg.REG_EXPAND_SZ, os.pathsep.join(entries)
            )
    except OSError:
        return False

    _broadcast_environment_change()
    return True


def _broadcast_environment_change() -> None:
    import ctypes

    try:
        ctypes.windll.user32.SendMessageTimeoutW(
            0xFFFF, 0x001A, 0, "Environment", 0x0002, 5000, ctypes.byref(ctypes.c_ulong())
        )
    except (OSError, AttributeError):
        # The PATH entry is already written; a missed broadcast only means
        # already-open programs keep the old environment until relaunch.
        pass


def _hold_step(status: Status, text: str, seconds: int = 8) -> None:
    """Keep `text` on the status line before the install proceeds.

    Used for warnings the user should be able to read and act on (e.g. macOS
    is untested): the line counts down once per second, any keypress on a real
    terminal skips the wait, and Ctrl+C aborts the install via the handler in
    main(). termios/tty are POSIX-only, which is fine: macOS is the only
    caller.
    """
    import select
    import termios
    import tty

    deadline = time.monotonic() + seconds
    fd = sys.stdin.fileno()
    interactive = sys.stdin.isatty()
    # One-keypress input mode (same as tty.setcbreak), with TCSADRAIN instead
    # of setcbreak's default TCSAFLUSH so keys typed before the wait started
    # are still delivered rather than flushed. Original mode is restored in
    # the finally below.
    old_mode = termios.tcgetattr(fd) if interactive else None
    if interactive:
        _ = tty.setcbreak(fd, termios.TCSADRAIN)
    try:
        while True:
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                return
            status.update(
                f"{text} — continuing in {math.ceil(remaining)}s "
                "— any key to skip, Ctrl+C to abort"
            )
            wait = min(1.0, remaining)
            if interactive:
                if select.select([sys.stdin], [], [], wait)[0]:
                    _ = sys.stdin.read(1)  # consume the key, proceed right away
                    return
            else:
                time.sleep(wait)
    finally:
        if old_mode is not None:
            termios.tcsetattr(fd, termios.TCSADRAIN, old_mode)


def _install_cli(args: argparse.Namespace, status: Status | None = None) -> Path:
    """Resolve (or build) the binary, install it, and return the launcher path.

    Every phase advances `status` (the run's single spinner line) when one is
    given; without one, progress is reported with plain prints instead.
    """
    if show_detected_os(status) == "macos" and status is not None:
        # Hold the yellow untested-platform warning on screen; see _hold_step.
        _hold_step(status, OS_STEPS["macos"])

    binary = args.binary
    if binary is None:
        show_step(status, STEPS["bin_check"])
        # A leftover dist/ binary is only trustworthy on a first install. Once
        # kvist is already installed, re-running install_cli.py means "update", so a
        # stale dist/ artifact must be rebuilt rather than reused.
        reinstalling = is_already_installed(args.lib_dir)
        if args.rebuild:
            binary = build_binary(status)
        elif reinstalling and find_default_binary() is not None:
            if status is None:
                print(f"kvist is already installed and a {BINARY_NAME} exists in dist/; rebuilding it ...")
            binary = build_binary(status)
        else:
            binary = find_default_binary()
            if binary is None:
                if status is None:
                    print(f"No {BINARY_NAME} found in dist/, building it ...")
                binary = build_binary(status)

    wrapper_path = install(binary.resolve(), args.lib_dir, args.bin_dir, status=status)
    show_step(status, STEPS["done"])
    hold_last_step()
    return wrapper_path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "binary",
        nargs="?",
        type=Path,
        help=f"Path to a prebuilt {BINARY_NAME}. If omitted and none is found, it gets built.",
    )
    parser.add_argument(
        "--rebuild",
        action="store_true",
        help="Build a fresh binary even if one is already found in dist/.",
    )
    parser.add_argument(
        "--lib-dir",
        type=Path,
        default=DEFAULT_LIB_DIR,
        help=f"Where to store the actual binary (default: {DEFAULT_LIB_DIR}).",
    )
    parser.add_argument(
        "--bin-dir",
        type=Path,
        default=DEFAULT_BIN_DIR,
        help=f"Where to place the `kvist` launcher (default: {DEFAULT_BIN_DIR}).",
    )
    parser.add_argument(
        "-v",
        "--verbose",
        action="store_true",
        help="Show the full output of pip and PyInstaller instead of a spinner.",
    )
    args = parser.parse_args()

    # Quiet unless asked otherwise: every command's output goes to the log and
    # a single spinner names the step. spinner() yields None when there is
    # nobody to show it to (verbose, no rich, no terminal), and every step
    # falls back to a plain print on None.
    if not args.verbose:
        begin_quiet_mode(LOG_FILE)
    try:
        with spinner(STEPS["starting"]) as status:
            wrapper_path = _install_cli(args, status)
    except InstallCommandError as exc:
        # Reported out here on purpose: leaving the `with` above already
        # stopped the spinner and erased its line, so this cannot print over it.
        report_command_failure(exc)
        raise SystemExit(1) from None
    except KeyboardInterrupt:
        # Ctrl+C during any step (most useful while a warning is held on
        # screen) aborts cleanly instead of ending in a raw traceback.
        print("Installation cancelled.", file=sys.stderr)
        raise SystemExit(130) from None
    finally:
        close_log()

    print(f"Installed core binary to {args.lib_dir / CORE_NAME}")
    print(f"Installed launcher to {wrapper_path}")

    if not path_contains(args.bin_dir):
        if IS_WINDOWS and add_to_user_path_windows(args.bin_dir):
            print(
                f"\nAdded {args.bin_dir} to your user PATH. Open a new terminal, "
                "then run `kvist` in any directory to start the agent there."
            )
        elif IS_WINDOWS:
            print(
                f"\nWarning: could not update PATH automatically. Add {args.bin_dir} "
                "yourself, e.g. in PowerShell:\n"
                '  [Environment]::SetEnvironmentVariable("Path", '
                '[Environment]::GetEnvironmentVariable("Path", "User") + '
                f'";{args.bin_dir}", "User")\n'
                "  (then restart your terminal)"
            )
        else:
            print(
                f"\nWarning: {args.bin_dir} is not on your PATH. Add it, e.g.:\n"
                f"  {path_hint(args.bin_dir)}\n"
                "  (then open a new terminal)"
            )
    else:
        print("\nDone. Run `kvist` in any directory to start the agent there.")


if __name__ == "__main__":
    sys.exit(main())
