def venv_python(venv_dir: Path) -> Path:
    if IS_WINDOWS:
        return venv_dir / "Scripts" / "python.exe"
    return venv_dir / "bin" / "python"


def _has_shared_libpython(python_exe: str) -> bool:
    # Only Linux needs one: Windows and macOS builds (macOS framework builds
    # report Py_ENABLE_SHARED=0) are bundled by PyInstaller as they are.
    if not sys.platform.startswith("linux"):
        return True
    result = probe_command(
        [python_exe, "-c", "import sysconfig; print(sysconfig.get_config_var('Py_ENABLE_SHARED'))"]
    )
    return result.returncode == 0 and result.stdout.strip() == "1"


def _python_sysconfig_info(python_exe: str) -> dict[str, object]:
    """Ask python_exe for the sysconfig facts PyInstaller depends on."""
    probe = (
        "import json, sys, sysconfig;"
        "print(json.dumps({"
        "'version': '%d.%d.%d' % sys.version_info[:3],"
        "'executable': sys.executable,"
        "'Py_ENABLE_SHARED': sysconfig.get_config_var('Py_ENABLE_SHARED'),"
        "'LIBDIR': sysconfig.get_config_var('LIBDIR'),"
        "'LDLIBRARY': sysconfig.get_config_var('LDLIBRARY'),"
        "}))"
    )
    result = probe_command([python_exe, "-c", probe], timeout=60)
    if result.returncode != 0:
        raise SystemExit(f"error: cannot inspect {python_exe}: {result.stderr.strip()}")
    output = result.stdout
    try:
        return json.loads(output)
    except ValueError:
        raise SystemExit(f"error: unexpected output from {python_exe}: {output!r}") from None


def _distro_hints(commands: dict[str, str]) -> str:
    """Per-distribution install commands, one per line, for error messages."""
    return "\n".join(f"      {distro:<15}{command}" for distro, command in commands.items())


def find_system_library(python_exe: str, status: Status | None = None) -> str:
    """Check PyInstaller's OS prerequisites; return the shared libpython path.

    PyInstaller can only bundle an interpreter built with a shared libpython,
    and on Linux it additionally needs GNU binutils' objdump to read the
    dynamic-library table of every dependency it bundles. This is the fail-fast
    gate for the build: a missing prerequisite stops the installer with install
    instructions instead of a cryptic PyInstaller traceback. Returns "" on
    platforms where no system check applies (Windows/macOS).

    `status` (optional) advances a spinner line through each prerequisite
    check; the red failure texts are shown right before the error is raised.
    """
    if not sys.platform.startswith("linux"):
        return ""

    show_step(status, STEPS["check_libpython"])
    info = _python_sysconfig_info(python_exe)
    version_short = ".".join(str(info.get("version", "?")).split(".")[:2])
    libdir = str(info.get("LIBDIR") or "")
    ldlibrary = str(info.get("LDLIBRARY") or "")
    libpython = os.path.join(libdir, ldlibrary) if libdir and ldlibrary else ""
    problems: list[str] = []

    # Shared libpython: sysconfig must know LIBDIR/LDLIBRARY and the file must
    # actually exist (some pythons report --enable-shared without shipping it).
    libpython_ok = True
    if str(info.get("Py_ENABLE_SHARED")) != "1" or not libpython:
        libpython_ok = False
        problems.append(
            f"Python {info.get('version')} ({info.get('executable')}) was built without a "
            "shared libpython "
            f"(Py_ENABLE_SHARED={info.get('Py_ENABLE_SHARED')!r}, LIBDIR={libdir!r}, "
            f"LDLIBRARY={ldlibrary!r}); PyInstaller can only bundle an interpreter built "
            "with --enable-shared.\n"
            "    Install a python3 built with --enable-shared, e.g.:\n"
            + _distro_hints(
                {
                    "Debian/Ubuntu:": "sudo apt install python3 python3-dev",
                    "Fedora/RHEL:": "sudo dnf install python3 python3-devel",
                    "Arch:": "sudo pacman -S python",
                }
            )
        )
    elif not os.path.isfile(libpython):
        libpython_ok = False
        problems.append(
            f"sysconfig reports a shared libpython that is not installed:\n"
            f"    LIBDIR={libdir!r}\n"
            f"    LDLIBRARY={ldlibrary!r}\n"
            f"    (expected {libpython})\n"
            "    Install the matching runtime, e.g.:\n"
            + _distro_hints(
                {
                    "Debian/Ubuntu:": f"sudo apt install libpython{version_short}-dev",
                    "Fedora/RHEL:": "sudo dnf install python3-libs",
                    "Arch:": "sudo pacman -S python",
                }
            )
        )
    show_step(status, STEPS["libpython_found" if libpython_ok else "libpython_missing"])

    # objdump: PyInstaller parses the dynamic-library table of every dependency.
    show_step(status, STEPS["check_objdump"])
    objdump_ok = shutil.which("objdump") is not None
    if not objdump_ok:
        problems.append(
            "objdump was not found on PATH; PyInstaller needs GNU binutils' objdump to "
            "inspect the shared libraries the binary links against.\n"
            "    Install binutils, e.g.:\n"
            + _distro_hints(
                {
                    "Debian/Ubuntu:": "sudo apt install binutils",
                    "Fedora/RHEL:": "sudo dnf install binutils",
                    "Arch:": "sudo pacman -S binutils",
                }
            )
        )
    show_step(status, STEPS["objdump_found" if objdump_ok else "objdump_missing"])

    if problems:
        raise SystemExit(
            "error: PyInstaller prerequisites are missing, kvist cannot be built:\n\n"
            + "\n\n".join(f"  - {problem}" for problem in problems)
            + "\n\nFix the issues above, then re-run install_cli.py."
        )

    return libpython

def find_base_python() -> str:
    """Pick an interpreter PyInstaller can actually link against.

    Some systems have a python3 earlier on PATH that was built without
    --enable-shared (fine for normal use, but PyInstaller refuses it). Prefer
    sys.executable, but fall back to other interpreters on PATH that do have
    a shared libpython.
    """
    if IS_WINDOWS:
        return sys.executable

    candidates = [sys.executable, "python3", "/usr/bin/python3", "python"]
    seen: set[str] = set()
    for candidate in candidates:
        resolved = shutil.which(candidate) or candidate
        if resolved in seen or not Path(resolved).is_file():
            continue
        seen.add(resolved)
        if _has_shared_libpython(resolved):
            return resolved

    raise SystemExit(
        "error: no Python interpreter with a shared libpython was found (PyInstaller "
        "requires one). Install a python3 built with --enable-shared (e.g. via your "
        "system package manager) and re-run."
    )


def ensure_build_venv(status: Status | None = None) -> Path:
    """Create (or reuse) the dedicated build venv and install its dependencies.

    `status`, when given, advances a spinner line through the Python-environment
    steps; without one (piped output, no rich) the same progress is printed as
    plain lines instead.
    """
    python_path = venv_python(VENV_DIR)
    show_step(status, STEPS["venv_check"])
    if python_path.is_file() and not _has_shared_libpython(str(python_path)):
        show_step(status, STEPS["venv_needed"])
        log(f"{VENV_DIR} was built with an interpreter PyInstaller can't use; recreating")
        shutil.rmtree(VENV_DIR)

    if not python_path.is_file():
        base_python = find_base_python()
        show_step(status, STEPS["venv_needed"])
        log(f"creating build venv at {VENV_DIR} using {base_python}")
        run_logged([base_python, "-m", "venv", str(VENV_DIR)])
    else:
        show_step(status, STEPS["venv_found"])

    # Fail before any pip work if PyInstaller's OS prerequisites are missing
    # (shared libpython + objdump on Linux): find_system_library raises SystemExit
    # with per-distribution install instructions in that case.
    find_system_library(str(python_path), status)

    # the animated line appends its own pulsing ellipsis, so no literal one
    show_step(status, "Installing build dependencies")
    run_logged([str(python_path), "-m", "pip", "install", "--upgrade", "pip"])
    if REQUIREMENTS_FILE.is_file():
        run_logged([str(python_path), "-m", "pip", "install", "-r", str(REQUIREMENTS_FILE)])
    run_logged([str(python_path), "-m", "pip", "install", "--upgrade", "pyinstaller"])
    return python_path


def build_terminal_ui(status: Status | None = None) -> bool:
    """Build the Ink terminal UI bundle that kvist.spec packs into the binary.

    The UI is optional — it needs Node.js at build time and again at run time —
    so a missing npm or a failed build only costs the binary this UI (`--frontend
    tui` then falls back to the classic terminal). The step line says so, because
    a binary that quietly lacks it is exactly what this step exists to prevent.
    Returns whether a bundle exists afterwards.
    """
    npm = shutil.which("npm")
    if npm is None:
        if not UI_BUNDLE.is_file():
            show_step(status, STEPS["ui_no_npm"])
        return UI_BUNDLE.is_file()

    show_step(status, STEPS["build_ui"])
    try:
        if not (UI_DIR / "node_modules").is_dir():
            run_logged([npm, "install"], cwd=UI_DIR)
        run_logged([npm, "run", "build"], cwd=UI_DIR)
    except InstallCommandError as error:
        log(str(error))
        show_step(status, STEPS["ui_failed"])
        return False
    return UI_BUNDLE.is_file()


def build_glass(status: Status | None = None) -> bool:
    """Build Kvist Glass, which kvist.spec packs into the binary.

    Optional like the Ink UI: it needs Rust (``install_rust.py``) at build time,
    and Windows is skipped because its terminals have no kitty graphics. A
    missing cargo or a failed build only costs the binary Glass (``--frontend
    glass`` then falls back to the Ink UI). Returns whether a build exists.
    """
    if IS_WINDOWS:
        return False
    cargo = find_cargo()
    if cargo is None:
        show_step(status, STEPS["glass_no_cargo"])
        return GLASS_BINARY.is_file()
    show_step(status, STEPS["build_glass"])
    try:
        run_logged([cargo, "build", "--release", "--locked"], cwd=GLASS_DIR)
    except InstallCommandError as error:
        log(str(error))
        show_step(status, STEPS["glass_failed"])
        return False
    return GLASS_BINARY.is_file()


def build_binary(status: Status | None = None) -> Path:
    if not SPEC_FILE.is_file():
        raise SystemExit(f"error: spec file not found: {SPEC_FILE}")

    python_path = ensure_build_venv(status)
    build_terminal_ui(status)
    build_glass(status)

    show_step(status, STEPS["build_binary"])
    run_logged(
        [str(python_path), "-m", "PyInstaller", "--noconfirm", "--clean", str(SPEC_FILE)],
        cwd=PROJECT_ROOT,
    )

    built = PROJECT_ROOT / "dist" / BINARY_NAME
    if not built.is_file():
        raise SystemExit(f"error: build finished but binary not found at {built}")
    show_step(status, STEPS["build_done"])
    return built


