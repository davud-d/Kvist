export const lang = { current: "en" };

export function setLanguage(value) {
  lang.current = value === "ru" ? "ru" : "en";
  document.documentElement.lang = lang.current;
}

/** The cloud's own choice (the cookie its other pages set) first, then the browser's. */
export function detectLanguage() {
  const cookie = document.cookie.split("; ").find((part) => part.startsWith("kc_lang="));
  const chosen = cookie?.slice("kc_lang=".length);
  if (chosen === "ru" || chosen === "en") return chosen;
  return (navigator.language || "en").toLowerCase().startsWith("ru") ? "ru" : "en";
}

/** Remembers the choice where the rest of the cloud reads it, and redraws everything in it. */
export function chooseLanguage(value) {
  document.cookie = `kc_lang=${value}; max-age=${365 * 24 * 3600}; path=/; samesite=lax`;
  location.reload();
}

export function t(key) {
  return lang.current === "ru" ? (RU[key] ?? key) : (EN[key] ?? key);
}

export function localized(message) {
  const text = String(message ?? "");
  const at = text.indexOf(" / ");
  if (at < 0) return text;
  return lang.current === "ru" ? text.slice(at + 3) : text.slice(0, at);
}
